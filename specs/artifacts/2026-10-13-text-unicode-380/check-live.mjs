import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve('.tmp-explorer-380');
const suffix='... (line truncated to 2000 chars)';
const source='a'.repeat(1999)+'🙂tail\n'+'b'.repeat(1998)+'🙂tail\nBoundary review complete.';
const lines=['a'.repeat(1999)+suffix,'b'.repeat(1998)+'🙂'+suffix,'Boundary review complete.'];
const summaries=[];
for(const [scope,archive] of [['after','interrupted-archive'],['final','final-archive']]) {
  const run=`C:/Users/hengu/.codex/opencorvus-product-iteration/2026-10-13/text-unicode-380-${scope}`;
  const file=run+'/project/unicode-boundary.txt';
  const read=(name)=>JSON.parse(fs.readFileSync(path.join(root,archive,name),'utf8'));
  const canonical=read('canonical-current-conversations.json');
  assert.equal(fs.readFileSync(file,'utf8'),source);
  assert.equal(canonical.tools.length,1);
  assert.equal(canonical.outcomes.length,1);
  const request=JSON.parse(canonical.tools[0].data);
  assert.deepEqual({tool:request.tool,input:request.input},{tool:'read',input:{filePath:file,offset:1,limit:3}});
  const outcome=canonical.outcomes[0];
  assert.equal(outcome.requestPartID,canonical.tools[0].id);
  assert.equal(outcome.outcome,'completed');
  const expected=`<path>${file}</path>\n<type>file</type>\n<content>${lines.map((s,i)=>`${i+1}: ${s}`).join('\n')}\n\n(End of file - total 3 lines)\n</content>`;
  assert.equal(outcome.output,expected);
  assert.equal(outcome.metadata.preview,lines.join('\n'));
  assert.deepEqual({lines:outcome.metadata.lines,totalLines:outcome.metadata.totalLines},{lines:3,totalLines:3});
  const sources=canonical.parts.filter(p=>p.type==='source-file');
  assert.equal(sources.length,1);
  assert.deepEqual({path:sources[0].path.replaceAll('\\','/'),title:sources[0].title,provider:sources[0].provider},{path:file,title:'unicode-boundary.txt',provider:'opencorvus-read'});
  const completed=canonical.messages.filter(m=>m.role==='assistant'&&m.finish==='stop');
  assert.equal(completed.length,2);
  for(const message of completed) assert.equal(typeof message.time.completed,'number');
  const preflight=read(`text-unicode-380-${scope}-preflight-ready.json`).preflight;
  assert.deepEqual({credential:preflight.credential,catalog:preflight.catalog,model:preflight.actualModel,stream:preflight.streaming},{credential:'usable',catalog:'projected',model:'gpt-6.1-sol',stream:true});
  summaries.push({scope,canonicalOutput:'Exact full output and preview matched',sourceFile:'Exact complete original text matched',tools:1,sources:1,assistantCompleted:2,originalSettlement:scope==='after'?'UNVERIFIED: interrupted owner/output drain':'Checked below'});
}
const readFinal=(name)=>JSON.parse(fs.readFileSync(path.join(root,'final-live','text-unicode-380-final-'+name+'.json'),'utf8'));
const provider=readFinal('final-provider-audit');
assert.equal(provider.requests.length,5);
for(const request of provider.requests) assert.deepEqual({model:request.model,stream:request.streaming,status:request.status,reader:request.response_reader.state,end:request.response_reader.terminal.kind},{model:'gpt-6.1-sol',stream:true,status:200,reader:'settled',end:'eof'});
const settled=JSON.parse(fs.readFileSync(path.join(root,'final-archive/text-unicode-380-final-native-host-settled.json'),'utf8'));
assert.deepEqual({reason:settled.terminal.reason,exitCode:settled.terminal.exitCode,physical:settled.physicalCompletion,output:settled.outputDrainComplete,request:settled.requestCleanupComplete},{reason:'exited',exitCode:0,physical:true,output:true,request:true});
const cleanup=readFinal('physical-terminal-and-pair-cleanup');
assert.equal(cleanup.pairedCleanupComplete,true);
assert.equal(cleanup.physicalCompletion,true);
const qualified=readFinal('qualified-surface-completion');
assert.deepEqual({qualification:qualified.qualification,physical:qualified.physicalCompletion,eof:qualified.providerEOFRequests},{qualification:'NativeService',physical:true,eof:5});
const birth=Number(BigInt(settled.target.processInstanceID.slice(6))/10000n-62135596800000n);
const elapsedMs=Date.parse(settled.observedAtUtc)-birth;
assert.ok(elapsedMs<600000);
const result={summaries,final:{requests:5,stream:'HTTP 200 / EOF',elapsedMs,physical:'Normal native, output and request settlement; paired cleanup complete'},boundary:'Canonical persisted tool data and real process/provider receipts. UI screenshots were reviewed manually; no DOM, UI text or pixel assertions.'};
fs.writeFileSync(path.join(root,'runtime-check.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
