import fs from "node:fs/promises";
import assert from "node:assert/strict";
import Ajv2020 from "file:///D:/myhexin-local/opencorvus/packages/opencorvus/node_modules/ajv/dist/2020.js";
const [port,phase]=process.argv.slice(2);
const base=`http://127.0.0.1:${port}`;
const artifacts="D:/myhexin-local/opencorvus/specs/artifacts/2026-11-09-extension-error-details";
const doc=await (await fetch(`${base}/doc`)).json();
const schema=doc.paths["/global/skill/market/search"].get.responses["400"].content["application/json"].schema;
const validate=new Ajv2020({strict:false,allErrors:true,validateFormats:false}).compile({...schema,components:doc.components});
const response=await fetch(`${base}/global/skill/market/search?query=${"x".repeat(121)}&limit=10`);
const body=await response.json();
assert.equal(response.status,400);
assert.equal(validate(body),true,JSON.stringify(validate.errors));
assert.equal(body.data.message,"Request validation failed");
assert.equal(body.error.length,1);
assert.equal(body.error[0].code,"too_big");
assert.deepEqual(body.error[0].path,["query"]);
assert.equal(typeof body.error[0].message,"string");
assert.ok(body.error[0].message.length>0);
const requestID=response.headers.get("x-opencorvus-request-id");assert.ok(requestID);
const result={phase,date:new Date().toISOString(),status:response.status,requestID,body,schemaValid:true};
await fs.writeFile(`${artifacts}/${phase}-validation-response.json`,JSON.stringify(result,null,2)+"\n");
console.log(JSON.stringify(result));
